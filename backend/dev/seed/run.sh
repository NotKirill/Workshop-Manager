#!/bin/sh
# Fills the dev database with generic data (seed.sql), then generates the images and backup archives it refers to
# and uploads them to the dev bucket. Runs inside the seed container of compose.dev.yaml; see README.md
set -eu

FONT=/usr/share/fonts/dejavu/DejaVuSans-Bold.ttf
PALETTE="#1f6f78 #2b4c7e #7a3e65 #8a5a1e #3d6b35 #5b3f8c #9c3d3d #2f5d62"
TAB=$(printf '\t')
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

s3() {
    curl -sS --aws-sigv4 "aws:amz:${S3_REGION}:s3" --user "${S3_ACCESS_KEY}:${S3_SECRET_KEY}" "$@"
}

color() {
    echo "$PALETTE" | cut -d' ' -f$(($1 % 8 + 1))
}

# make_image FILE KIND LABEL VARIANT
make_image() {
    case $2 in
        cover) size=960x540 points=54 ;;
        shot) size=1280x720 points=44 ;;
        *) size=640x360 points=34 ;;
    esac
    width=${size%x*}
    magick -size "$size" "gradient:$(color "$4")-$(color $(($4 * 3 + 1)))" \
        \( -size "$((width * 85 / 100))x" -background none -fill white -font "$FONT" -pointsize "$points" \
           -gravity center "caption:$3" \) \
        -gravity center -composite \
        -fill '#ffffffb0' -font "$FONT" -pointsize 16 -gravity southwest -annotate +14+10 "$2 - seed data" \
        -quality 85 "$1"
}

# make_archive FILE LABEL VARIANT
make_archive() {
    dir="$WORK/archive"
    rm -rf "$dir"
    mkdir -p "$dir/data"
    printf '%s\n\nGenerated by the dev seed of Workshop Manager. Not a real mod.\n' "$2" > "$dir/README.txt"
    printf '{\n  "name": "%s",\n  "version": "1.%d"\n}\n' "$(printf '%s' "$2" | sed 's/[\\"]/\\&/g')" "$(($3 % 10))" \
        > "$dir/manifest.json"
    head -c $(((10 + $3 * 7919 % 600) * 1024)) /dev/urandom > "$dir/data/assets.bin"
    (cd "$dir" && zip -qr "$1" .)
}

echo "Seeding database ${PGDATABASE} on ${PGHOST}"
psql -X -q -v ON_ERROR_STOP=1 -v admin_steam_id="${ADMIN_STEAM_ID:-}" <<EOF
SET client_min_messages = warning;
CREATE TEMP TABLE seed_settings (with_files boolean NOT NULL DEFAULT false, admin_steam_id text);
INSERT INTO seed_settings VALUES (true, NULLIF(:'admin_steam_id', ''));
\i /seed/seed.sql
\copy seed_uploads TO '$WORK/uploads.tsv'
EOF

# The backend creates the bucket on start too; creating it here lets the seed run first. 409: it exists
code=$(s3 -o /dev/null -w '%{http_code}' -X PUT "${S3_ENDPOINT}/${S3_BUCKET}")
case $code in
    200 | 409) ;;
    *) echo "Cannot create bucket ${S3_BUCKET} (HTTP $code)" >&2; exit 1 ;;
esac

total=$(wc -l < "$WORK/uploads.tsv")
echo "Generating and uploading $total files to ${S3_ENDPOINT}/${S3_BUCKET}"
: > "$WORK/sizes.tsv"
done_count=0
while IFS="$TAB" read -r key kind label variant; do
    file="$WORK/files/$key"
    mkdir -p "$(dirname "$file")"
    case $kind in
        archive)
            make_archive "$file" "$label" "$variant"
            type=application/octet-stream
            ;;
        *)
            make_image "$file" "$kind" "$label" "$variant"
            case $file in
                *.png) type=image/png ;;
                *) type=image/jpeg ;;
            esac
            ;;
    esac
    if ! s3 --fail-with-body -o /dev/null -H "Content-Type: $type" -T "$file" "${S3_ENDPOINT}/${S3_BUCKET}/$key"; then
        echo "Upload of $key failed; the database already has the new data, run the seed again" >&2
        exit 1
    fi
    printf '%s\t%s\t%s\n' "$key" "$(stat -c %s "$file")" "$(sha256sum "$file" | cut -d' ' -f1)" >> "$WORK/sizes.tsv"
    rm -f "$file"
    done_count=$((done_count + 1))
    if [ $((done_count % 50)) -eq 0 ]; then
        echo "  $done_count / $total"
    fi
done < "$WORK/uploads.tsv"

echo "Writing file sizes and hashes"
psql -X -q -v ON_ERROR_STOP=1 <<EOF
CREATE TEMP TABLE seed_sizes (s3_key text PRIMARY KEY, size bigint NOT NULL, sha256 text NOT NULL);
\copy seed_sizes FROM '$WORK/sizes.tsv'
UPDATE media_files f SET file_size = s.size FROM seed_sizes s WHERE f.s3_key = s.s3_key;
UPDATE item_content_revisions r SET file_size = s.size, sha256 = s.sha256 FROM seed_sizes s WHERE r.s3_key = s.s3_key;
EOF

# Cached user data and one-time tokens belong to the old rows (the seed reuses ids 1, 2, ...)
echo "Clearing the Redis cache"
redis-cli -h "$REDIS_HOST" -a "$REDIS_PASSWORD" --no-auth-warning FLUSHDB > /dev/null

echo "Done. Sign in as admin / Admin123!dev, or see README.md for the other accounts."
