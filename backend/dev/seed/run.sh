#!/bin/sh
# Dev seed, run in the seed container of compose.dev.yaml. See README.md
#   run.sh [seed]    load snapshot.sql, then generate and upload the files it uses
#   run.sh snapshot  save the dev database as snapshot.sql and files.tsv
set -eu

SEED=/seed
# Dates in snapshot.sql count from here
ANCHOR='2000-01-01 00:00:00+00'
SNAPSHOT_DB=seed_snapshot
FONT=/usr/share/fonts/dejavu/DejaVuSans-Bold.ttf
PALETTE="#1f6f78 #2b4c7e #7a3e65 #8a5a1e #3d6b35 #5b3f8c #9c3d3d #2f5d62"
TAB=$(printf '\t')
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

fail() {
    echo "$*" >&2
    exit 1
}

s3() {
    curl -sS --aws-sigv4 "aws:amz:${S3_REGION}:s3" --user "${S3_ACCESS_KEY}:${S3_SECRET_KEY}" "$@"
}

color() {
    echo "$PALETTE" | cut -d' ' -f$(($1 % 8 + 1))
}

# make_image FILE KIND LABEL VARIANT
make_image() {
    case $2 in
        cover) size=960x540 points=54 ;;
        shot) size=1280x720 points=44 ;;
        *) size=640x360 points=34 ;;
    esac
    width=${size%x*}
    magick -size "$size" "gradient:$(color "$4")-$(color $(($4 * 3 + 1)))" \
        \( -size "$((width * 85 / 100))x" -background none -fill white -font "$FONT" -pointsize "$points" \
           -gravity center "caption:$3" \) \
        -gravity center -composite \
        -fill '#ffffffb0' -font "$FONT" -pointsize 16 -gravity southwest -annotate +14+10 "$2 - seed data" \
        -strip -define png:exclude-chunks=date,time -quality 85 "$1"
}

# make_archive FILE LABEL VARIANT
make_archive() {
    dir="$WORK/archive"
    rm -rf "$dir"
    mkdir -p "$dir/data"
    printf '%s\n\nGenerated by the dev seed of Workshop Manager. Not a real mod.\n' "$2" > "$dir/README.txt"
    printf '{\n  "name": "%s",\n  "version": "1.%d"\n}\n' "$(printf '%s' "$2" | sed 's/[\\"]/\\&/g')" "$(($3 % 10))" \
        > "$dir/manifest.json"
    yes "seed data $3" | head -c $(((10 + $3 * 7919 % 600) * 1024)) > "$dir/data/assets.bin"
    # No compression and fixed dates: the same archive every run
    find "$dir" -exec touch -d '2000-01-01 00:00:00' {} +
    (cd "$dir" && zip -q -0 -X "$1" README.txt manifest.json data/assets.bin)
}

seed() {
    # The schema gets dropped, so nothing else may be connected
    others=$(psql -X -At -c "SELECT coalesce(nullif(application_name, ''), 'unnamed client')
        FROM pg_stat_activity
        WHERE datname = current_database() AND backend_type = 'client backend' AND pid <> pg_backend_pid()" \
        | sort | uniq -c)
    if [ -n "$others" ]; then
        fail "Other connections to ${PGDATABASE}: stop the backend and close database consoles, then run the seed again
$others"
    fi

    echo "Loading the snapshot into ${PGDATABASE} on ${PGHOST}"
    psql -X -q -o /dev/null -v ON_ERROR_STOP=1 --single-transaction \
        -v anchor="$ANCHOR" -v admin_steam_id="${ADMIN_STEAM_ID:-}" -f "$SEED/sql/restore.sql"

    # The backend creates it too, but the seed may run first. 409: it exists
    code=$(s3 -o /dev/null -w '%{http_code}' -X PUT "${S3_ENDPOINT}/${S3_BUCKET}")
    case $code in
        200 | 409) ;;
        *) fail "Cannot create bucket ${S3_BUCKET} (HTTP $code)" ;;
    esac

    total=$(wc -l < "$SEED/files.tsv")
    echo "Generating and uploading $total files to ${S3_ENDPOINT}/${S3_BUCKET}"
    : > "$WORK/sizes.tsv"
    done_count=0
    while IFS="$TAB" read -r key kind label variant; do
        file="$WORK/files/$key"
        mkdir -p "$(dirname "$file")"
        case $kind in
            archive)
                make_archive "$file" "$label" "$variant"
                type=application/octet-stream
                ;;
            *)
                make_image "$file" "$kind" "$label" "$variant"
                case $file in
                    *.png) type=image/png ;;
                    *) type=image/jpeg ;;
                esac
                ;;
        esac
        if ! s3 --fail-with-body -o /dev/null -H "Content-Type: $type" -T "$file" "${S3_ENDPOINT}/${S3_BUCKET}/$key"; then
            fail "Upload of $key failed; the database already has the new data, run the seed again"
        fi
        printf '%s\t%s\t%s\n' "$key" "$(stat -c %s "$file")" "$(sha256sum "$file" | cut -d' ' -f1)" >> "$WORK/sizes.tsv"
        rm -f "$file"
        done_count=$((done_count + 1))
        if [ $((done_count % 50)) -eq 0 ]; then
            echo "  $done_count / $total"
        fi
    done < "$SEED/files.tsv"

    echo "Writing file sizes and hashes"
    psql -X -q -v ON_ERROR_STOP=1 -f "$SEED/sql/write-sizes.sql" < "$WORK/sizes.tsv"

    # Cached users and tokens belong to the old rows
    echo "Clearing the Redis cache"
    redis-cli -h "$REDIS_HOST" -a "$REDIS_PASSWORD" --no-auth-warning FLUSHDB > /dev/null

    echo "Done. Start the backend: Liquibase applies the migrations newer than the snapshot."
    echo "Sign in as admin / Admin123!dev, or see README.md for the other accounts."
}

# Saves the dev database and the list of files to generate
snapshot() {
    [ -w "$SEED" ] || fail "Cannot write to $SEED: run the snapshot with --user \"\$(id -u):\$(id -g)\" (README.md)"

    echo "Dumping ${PGDATABASE}"
    # Sessions, nonces, uploads in progress and scheduler state stay out
    pg_dump --no-owner --no-privileges \
        --exclude-table-data='qrtz_*' --exclude-table-data=refresh_tokens \
        --exclude-table-data=open_id_nonces --exclude-table-data=content_uploads > "$WORK/dump.sql"
    # When the seed last ran (now, if it never did)
    restored_at=$(psql -X -At -c "SELECT coalesce(current_setting('seed.restored_at', true), now()::text)")

    # Dates and your Steam ID change in a copy, not in the dev database
    psql -X -q -v ON_ERROR_STOP=1 -c "SET client_min_messages = warning" \
        -c "DROP DATABASE IF EXISTS $SNAPSHOT_DB" -c "CREATE DATABASE $SNAPSHOT_DB"
    psql -X -q -o /dev/null -v ON_ERROR_STOP=1 -d "$SNAPSHOT_DB" -f "$WORK/dump.sql"
    psql -X -q -v ON_ERROR_STOP=1 -d "$SNAPSHOT_DB" \
        -v anchor="$ANCHOR" -v restored_at="$restored_at" -v admin_steam_id="${ADMIN_STEAM_ID:-}" \
        -f "$SEED/sql/prepare-snapshot.sql"

    echo "Listing stored files"
    psql -X -q -v ON_ERROR_STOP=1 -d "$SNAPSHOT_DB" -f "$SEED/sql/list-files.sql" > "$WORK/files.tsv"

    {
        echo "-- Dev seed snapshot, written by run.sh snapshot. Don't edit by hand."
        echo "-- Dates count from $ANCHOR; the seed moves them to the time it runs."
        echo
        # Fixed key: same data, same file
        pg_dump -d "$SNAPSHOT_DB" --no-owner --no-privileges --restrict-key=devseed
    } > "$WORK/snapshot.sql"
    psql -X -q -c "DROP DATABASE $SNAPSHOT_DB"

    cp "$WORK/snapshot.sql" "$SEED/snapshot.sql"
    cp "$WORK/files.tsv" "$SEED/files.tsv"
    echo "Saved snapshot.sql and files.tsv ($(wc -l < "$SEED/files.tsv") files)"
}

case ${1:-seed} in
    seed) seed ;;
    snapshot) snapshot ;;
    *) fail "Usage: run.sh [seed | snapshot]" ;;
esac
